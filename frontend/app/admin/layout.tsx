export default function AdminLayout({ children }: { children: React.ReactNode }) {
  const router = useRouter();
  const pathname = usePathname();
  const [checking, setChecking] = useState(true);

  useEffect(() => {
    if (pathname === "/admin/login") { setChecking(false); return; }
    const token = localStorage.getItem("admin_token");
    if (!token) {
      // Don't set checking=false here — keep rendering the spinner
      // until the redirect completes so child pages never mount without a token
      router.replace("/admin/login");
    } else {
      setChecking(false);
    }
  }, [pathname, router]);

  const handleLogout = () => {
    localStorage.removeItem("admin_token");
    router.replace("/admin/login");
  };

  if (pathname === "/admin/login") return <>{children}</>;
  if (checking) return (
    <div className="min-h-screen bg-background flex items-center justify-center">
      <div className="w-8 h-8 border-2 border-gold border-t-transparent rounded-full animate-spin" />
    </div>
  );

  return (
    <div className="min-h-screen bg-background flex">
      {/* Sidebar */}
      <aside className="w-56 bg-background-secondary border-r border-border flex flex-col shrink-0">
        <div className="px-5 py-6 border-b border-border">
          <span className="font-display font-bold text-gold tracking-widest text-sm uppercase">MI Admin</span>
          <p className="text-silver-dark text-xs mt-0.5">Moon Ideas</p>
        </div>

        <nav className="flex-1 px-3 py-4 flex flex-col gap-1" aria-label="Admin navigation">
          {navItems.map((item) => {
            const active = pathname.startsWith(item.href);
            return (
              <Link
                key={item.href}
                href={item.href}
                className={`flex items-center gap-3 px-3 py-2.5 rounded-md text-sm font-sans transition-all duration-150 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-gold ${
                  active
                    ? "bg-gold/10 text-gold border border-gold/20"
                    : "text-silver hover:text-brand-white hover:bg-background-elevated"
                }`}
              >
                {item.icon}
                {item.label}
              </Link>
            );
          })}
        </nav>

        <div className="px-3 py-4 border-t border-border">
          <button
            onClick={handleLogout}
            className="flex items-center gap-3 px-3 py-2.5 rounded-md text-sm text-silver hover:text-red-400 hover:bg-background-elevated w-full transition-all duration-150 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-gold"
          >
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.75" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
              <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
              <polyline points="16 17 21 12 16 7" />
              <line x1="21" y1="12" x2="9" y2="12" />
            </svg>
            Logout
          </button>
        </div>
      </aside>

      <main className="flex-1 overflow-auto">{children}</main>
    </div>
  );
}
